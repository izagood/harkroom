/**
 * 창 최상단 바 한 줄의 높이(#359).
 *
 * 사이드바 브랜드 바와 `Workspace` 헤더는 **가로로 나란히 붙어 한 줄처럼 보인다.** 그런데
 * 각자 세로 여백(`py-3`·`py-1`)으로 높이를 따로 만들고 있어서 아래 경계가 어긋났다 —
 * 실측으로 브랜드 바 48px, 헤더 32px 이었다.
 *
 * 여백이 아니라 **높이를 못박아** 둘이 같은 값을 쓴다. 안쪽은 `items-center` 가 세로
 * 가운데를 맞추므로, 한쪽 내용이 바뀌어도 경계는 계속 맞는다. 여백으로 맞추면 폰트나
 * 아이콘 크기가 바뀔 때마다 두 숫자를 같이 고쳐야 하고, 한쪽만 고치는 순간 다시 어긋난다.
 *
 * **36px 은 두 제약 사이에서 고른 값이다.** 위로는 옛 브랜드 바(48px)처럼 두꺼우면 타이틀바로
 * 보이지 않고 화면 위쪽을 낭비한다. 아래로는 신호등 높이에 딱 맞춘 28px(`MAC_TITLEBAR_H`)이면
 * 로고·`harkroom`·`←` 가 위아래로 눌려 답답하다.
 *
 * **신호등이 이 띠의 세로 가운데에 온다**(macOS 26 실측, 2026-09-30). 창에 빈 툴바를 달아
 * (`src-tauri/src/window_chrome.rs`) 신호등 중심이 창 위 약 19.75pt 로 내려왔다. 이 띠의 가운데는
 * 배율(`lib/zoom.ts`) 100% 에서 18pt, 110% 에서 19.8pt 라 신호등이 가운데 ±2pt 안에 선다.
 * 툴바를 달기 전에는 신호등 중심이 약 15.75pt 라 110% 기준 위로 4pt 치우쳐, 창 꼭대기에 붙어
 * 보였다. 배율은 띠만 키우고 신호등은 OS 가 정한 자리에 두므로 완전한 가운데는 한 배율뿐이다.
 *
 * 손잡이 띠(`MAC_TITLEBAR_H`)와는 **일부러 다른 값이다.** 띠는 좌상단에 바가 없는 화면에서
 * "원래 타이틀바가 있던 자리"만 끌리게 하는 것이라 그 높이를 넘으면 안 되지만, 이 바는
 * 실제로 내용을 담는다.
 */
export const TOP_BAR_H = 'h-9';

