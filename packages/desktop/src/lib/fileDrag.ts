/**
 * 파일을 든 드래그인가 — **끌어다 놓기의 판정 한 곳**.
 *
 * 컴포저의 놓을 자리(오버레이)와 창 전체의 안전망이 같은 질문을 한다. 둘이 각자
 * 판정하면 한쪽만 고치는 날이 오고, 그때 증상은 "표시는 뜨는데 안 받는다"(또는 그 반대)로
 * 나타난다 — 원인에서 가장 먼 증상이다.
 *
 * 글자나 멘션 칩을 끄는 것은 파일이 아니다. 그것까지 파일로 보면 컴포저 안에서 글자를
 * 옮기는 평범한 동작마다 오버레이가 뜨고, 창 안전망이 기본 동작을 막아 **글자 이동 자체가
 * 죽는다.**
 */
export const isFileDrag = (dt: DataTransfer | null): boolean =>
  Array.from(dt?.types ?? []).includes('Files');
