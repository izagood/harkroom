/**
 * 레일 네 칸의 아이콘(#2 의 요구: "Home, DM, Agents, Saved 여기서 쓰는 아이콘 첨부한 이미지
 * 처럼 아이콘 형식으로 수정해줘").
 *
 * ## 왜 이모지를 버리는가
 *
 * 넷은 이모지였다(`🏠 💬 🤖 🔖`). 이모지는 **OS 가 그린다** — 그래서 세 가지가 우리 손을
 * 벗어난다:
 *
 * - **색.** 이모지는 자기 색을 들고 온다. 고른 칸(`text-fg`)과 안 고른 칸(`text-fg-muted`)의
 *   구분이 아래 라벨에만 걸리고 그림은 늘 같은 색이라, 레일에서 지금 어디에 있는지가
 *   절반만 보인다. 라이트·다크 모드에도 반응하지 않는다.
 * - **크기.** 이모지의 실제 잉크 높이는 폰트마다 다르고 `text-*` 로는 상자만 정해진다.
 *   그래서 넷의 시각적 무게가 서로 어긋났다(집·말풍선은 꽉 차고 책갈피는 작다).
 * - **모양.** 플랫폼마다 다른 그림이 나온다. 참고 이미지가 요구하는 것은 **한 벌의 선
 *   아이콘**이고, 이모지로는 그 한 벌을 만들 수 없다.
 *
 * 그래서 `currentColor` 로 그리는 선 아이콘으로 바꾼다 — 색은 칸이 정하고(고른 칸에서
 * 저절로 진해진다), 크기는 `viewBox` 가 정하고, 모양은 이 파일 하나가 정한다.
 *
 * ## 한 벌로 보이게 하는 규칙
 *
 * 넷이 같은 격자에서 나와야 한 벌로 보인다: **24 격자 · 선 굵기 1.6 · 둥근 끝과 이음 ·
 * 채움 없음**, 그리고 잉크는 24 안에서 3~21 사이에 둔다. 굵기를 아이콘마다 다르게 하거나
 * 하나만 채우면 그 하나가 다른 세트에서 온 것처럼 보인다.
 *
 * `aria-hidden` 이다 — 칸 버튼이 `aria-label` 로 이미 이름을 말한다(`Rail.tsx`). 그림에
 * 이름을 또 주면 스크린리더가 같은 것을 두 번 읽는다.
 */
import type { ReactNode } from 'react';

export type RailIconName = 'home' | 'dm' | 'agents' | 'saved';

/**
 * 이름 → 경로. **배열이 아니라 표다** — `RAIL_CELLS` 의 순서가 단축키를 정하므로
 * 그 순서를 여기서 한 번 더 적으면 두 곳이 갈라진다(그 파일 주석의 근거와 같다).
 */
const PATHS: Record<RailIconName, ReactNode> = {
  /* 집 — 지붕은 한 선, 몸통은 아래를 열어 둔다(바닥은 아이콘 상자의 밑변이 대신한다). */
  home: (
    <>
      <path d="M3.5 10.6 12 3.75l8.5 6.85" />
      <path d="M5.9 9.6V19.5a1.25 1.25 0 0 0 1.25 1.25h9.7a1.25 1.25 0 0 0 1.25-1.25V9.6" />
    </>
  ),
  /* 말풍선 — 꼬리가 왼쪽 아래다. 참고 이미지의 DM 칸과 같은 방향이다. */
  dm: (
    <path d="M20.75 11.6a8.4 8.4 0 0 1-8.6 8.4 9 9 0 0 1-3.5-.7L3.6 20.4l1.2-4.6a8.2 8.2 0 0 1-1.05-4.2 8.4 8.4 0 0 1 8.6-8.4 8.4 8.4 0 0 1 8.4 8.4Z" />
  ),
  /*
    에이전트 — 머리 상자에 더듬이와 눈 둘. **사람 얼굴을 쓰지 않는다**: 이 앱에서 원 안의
    얼굴은 이미 계정 아바타(`Identity`)가 쓰는 모양이라, 레일 칸이 그것을 쓰면 "누구"와
    "무엇" 이 같은 그림이 된다.
  */
  agents: (
    <>
      <path d="M12 6.4V4.2" />
      <path d="M12 3.05v.05" />
      <rect x="4.25" y="6.4" width="15.5" height="12.6" rx="3.2" />
      <path d="M9.4 11.9v1.6" />
      <path d="M14.6 11.9v1.6" />
      <path d="M9.6 16.3h4.8" />
    </>
  ),
  /* 책갈피 — 참고 이미지의 `나중에` 칸과 같은 모양이다. 담아 둔 것이 곧 나중에 볼 것이다. */
  saved: (
    <path d="M6.75 3.9h10.5a1 1 0 0 1 1 1v15.2l-6.25-3.9-6.25 3.9V4.9a1 1 0 0 1 1-1Z" />
  ),
};

export function RailIcon({ name, className = '' }: { name: RailIconName; className?: string }) {
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 24 24"
      className={`h-5 w-5 ${className}`}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.6"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {PATHS[name]}
    </svg>
  );
}
