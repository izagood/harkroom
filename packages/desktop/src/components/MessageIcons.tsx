import type { ReactElement } from 'react';

/**
 * 메시지 툴바 여덟 칸의 아이콘(요청 2026-09-09 — 첨부 화면을 놓고 "사용성이 너무 별로"라고
 * 지적한 그 자리다).
 *
 * ## 왜 이모지가 아니라 그림인가
 *
 * 앞 판의 툴바는 `＋` 와 `↩` 와 `⋯` 를 **글자로** 그렸다. 레일이 같은 이유로 이모지를
 * 버렸고(`RailIcons.tsx` 머리말), 그 근거가 여기서도 그대로 성립한다: 글자는 폰트가 정하는
 * 그림이라 OS 마다 모양이 다르고, 크기가 글자 크기라 타이포 4단의 예외를 만들어야 하고,
 * `↩` 는 그중에서도 폰트마다 굵기 차이가 커서 옆 이모지들과 무게가 맞지 않았다.
 *
 * ## 관례는 레일과 하나다
 *
 * **24 격자 · 선 굵기 1.5 · `currentColor` · 끝은 둥글게.** 저장소에 이미 손으로 그린
 * 아이콘이 셋 있고(`Logo` · `SidebarToggleIcon` · `RailIcons`) 넷째 벌을 만들지 않는다.
 * 아이콘 라이브러리를 넣지 않는 이유도 그 파일에 적힌 그대로다 — 넷을 위해 의존성을
 * 늘리지 않는다.
 *
 * **담기 버튼은 여기 없다.** 그 그림은 `RailIcons.SavedIcon` 을 그대로 쓴다 — 레일의
 * `Saved` 칸 · 메시지의 담김 표식 · 툴바의 담기 버튼이 **같은 그림이어야** 사람이 셋을
 * 한 가지로 읽는다(그 파일이 `size` 를 여는 이유가 이것이다).
 *
 * `aria-hidden` 이다 — 이름은 버튼의 `aria-label` 이 진다. 그림이 이름을 또 내면
 * 스크린리더가 칸 하나를 두 번 읽는다.
 */
function Icon({ children, size = 16 }: { children: ReactElement | ReactElement[]; size?: number }): ReactElement {
  return (
    <svg
      aria-hidden="true"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.5"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {children}
    </svg>
  );
}

/**
 * 리액션 고르기 — 웃는 얼굴에 `+`.
 *
 * 그냥 `＋` 였다. 그 글자는 "무언가 더한다"까지만 말하고 **무엇을** 더하는지는 말하지
 * 않는다 — 옆 칸이 이모지 셋이라 문맥이 그것을 메워 주기를 기대한 것인데, 그 셋도 호버
 * 전에는 안 보인다. 얼굴을 그려 두면 버튼 하나가 스스로 "이모지"라고 말한다.
 *
 * 원의 오른쪽 위를 **열어 둔다**(호를 270°만 그린다) — `+` 가 원 밖에 붙으면 16px 에서
 * 두 덩어리로 갈려 보이고, 원 안에 넣으면 눈·입과 겹친다. 열린 틈에 놓으면 하나의 그림이다.
 */
export function EmojiPlusIcon(): ReactElement {
  return (
    <Icon>
      <path d="M20.4 12.9a8.5 8.5 0 1 1-9.3-9.3" />
      <path d="M7.6 15.2a4.6 4.6 0 0 0 6.8 0" />
      <path d="M8.4 10.2h.01M13.6 10.2h.01" strokeWidth="2.2" />
      <path d="M18.5 3.2v4.6M16.2 5.5h4.6" />
    </Icon>
  );
}

/**
 * 스레드 — **들여쓴 답글 줄**(후보 다섯 중 사람이 고른 것, 2026-09-10).
 *
 * 위의 긴 줄이 이 말이고, 아래로 꺾여 들어가는 줄이 그 아래 붙는 답글이다. 이 뜻을 고른
 * 근거는 **앱이 이미 같은 것을 글자로 말하고 있다는 점**이다 — 본문 열의 「답글 3개」 줄이
 * 가리키는 것이 바로 "이 말 아래에 붙은 것들"이고, 그림과 글이 같은 것을 말하면 둘이 서로를
 * 설명한다.
 *
 * 후보였던 것들과 왜 갈렸는지도 남긴다(같은 자리를 다시 고민하지 않게):
 * - **답글 화살표(`↩`)** — 지금 화면의 그림이지만 메일의 "회신"과 같아, 스레드가
 *   *이어지는 자리*라는 뜻은 싣지 못한다.
 * - **말풍선 + 화살표** — 뜻은 정확한데 16px 에 선이 다섯이라 다크에서 뭉친다.
 * - **겹친 말풍선 둘** — 레일의 `DmIcon` 이 말풍선 하나여서 축소되면 헷갈린다.
 * - **갈라진 가지** — 구조는 정확하지만 git 브랜치로 읽힌다.
 *
 * 마지막 줄에 꺾임(elbow)을 둔 것은 장식이 아니다. 세 줄을 나란히 두면 **문단 정렬**
 * 아이콘이 되어 버린다 — 꺾여 내려가는 획 하나가 "정렬"과 "답글"을 가른다.
 */
export function ThreadIcon(): ReactElement {
  return (
    <Icon>
      <path d="M4 6h16" />
      <path d="M4 10.4h9" />
      <path d="M4 14v2.6a2.6 2.6 0 0 0 2.6 2.6H16" />
    </Icon>
  );
}

