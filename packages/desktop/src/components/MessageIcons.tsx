/**
 * 더 보기 — 점 셋.
 *
 * `⋯`(U+22EF) 였다. 그 글자는 폰트마다 점의 지름과 간격이 다르고, 무엇보다 **선이 아니라
 * 면**이라 옆 칸의 1.5px 획들과 무게가 맞지 않았다(그 자리만 흐리거나 그 자리만 진했다).
 * 원 셋을 직접 그리면 지름이 우리 값이다.
 */
