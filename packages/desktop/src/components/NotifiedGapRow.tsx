import { useActiveStore } from '../state/communities';

/**
 * **집합 호출의 결과** — 셋을 불렀는데 둘만 깼다는 한 줄.
 *
 * 정본 문서 `docs/desktop-design-directions.html` 의 진단: *"집합 호출의 결과가 안 보인다.
 * 셋을 불러 둘만 깨어나도 화면은 아무 말도 하지 않는다."* 처방은 *"보내기 전엔 몇 명인지,
 * 보낸 뒤엔 누가 깼는지"* 이고, 앞의 절반은 이미 있다(작성창의 "부를 상대" 목록 + 후보의
 * `memberCount`). 이 줄이 뒤의 절반이다.
 *
 * ## 어디에 — 부른 자리 바로 아래
 *
 * 문서의 목업이 그 자리를 그렸다: 내가 보낸 메시지 아래에 *"집합 · release 3명을 불렀다 —
 * …"* 한 줄. `Notice`(#178)가 아닌 이유가 셋이다:
 *
 * 1. **`Notice` 는 화면 전역 띠 하나**다. 연달아 두 집합을 부르면 뒤의 것이 앞의 것을
 *    덮어쓰고, 사람은 어느 발화의 결과를 보고 있는지 모른다. 이 사실은 **발화당 하나**다.
 * 2. **`Notice` 는 사람이 손으로 닫는다.** 그것이 옳은 것은 "지금 놓치면 다시 볼 길이 없는
 *    실패"(클립보드 실패)이기 때문이다. 이 줄은 발화 옆에 남아 있으면 스크롤로 다시 읽힌다.
 * 3. **고치는 경로가 같은 자리에** 있어야 한다(문서, `FailureCard` 의 같은 절). 무엇을
 *    다시 부를지 정하는 것은 그 발화를 보면서 하는 일이다.
 *
 * `WakeRow` 와 같은 결의 줄이다 — 말풍선이 아니라 **상태 한 줄**(규칙 02). 발화가 아니므로
 * 리액션·툴바·스레드 컨트롤을 달지 않는다.
 *
 * ## 언제 — 덜 깼을 때만
 *
 * 문서: *"셋을 불렀는데 둘만 깨어난 것은 **조용한 실패**이고, 지금 화면은 그것을 말할
 * 자리가 없다."* 셋을 불러 셋이 깨면 **아무 말도 하지 않는다** — 성공까지 줄을 받으면 집합
 * 호출마다 줄이 하나씩 달리고, 그러면 덜 깬 발화의 줄이 나머지와 구별되지 않는다.
 * 규칙 06("없는 문은 그리지 않는다")을 결과 쪽에 적용한 것이고, `0 replies` 를 지운 것과
 * 같은 결이다. 판정은 `lib/notified.ts::notifiedSummary` 한 자리에 있고, 스토어에 키가
 * 없으면 이 컴포넌트는 아무것도 그리지 않는다.
 *
 * ## 강조색을 쓰지 않는다 (규칙 04)
 *
 * 강조는 **나를 막는 것**에만 준다(`test/accentBudget.test.tsx` 가 예산을 잰다). 덜 깬
 * 부름은 나를 막지 않는다 — 내 차례가 아니고, 내가 답해야 진행되는 것도 아니다. 그리고
 * **깬 사람들은 이미 일하고 있다**: 부름 자체가 실패한 것이 아니라 일부가 빠진 것이다.
 * `state-stuck`(실패 축)도 아니다 — 그것은 "에이전트가 스스로 못 끝냈다"이고, 여기서
 * 못 끝낸 것은 없다.
 *
 * 그래서 `warning` 축을 쓴다. `RunnerStatus.tsx` 의 `TONE` 이 같은 판단을 이미 적어 뒀다
 * ("러너는 떴는데 사람이 한 단계를 해야 한다"). 여기서 사람이 할 한 단계는 **그 사람을
 * 채널에 넣는 것**이다.
 *
 * ## 버튼이 없다 — 없는 문은 그리지 않는다 (규칙 06)
 *
 * 문서의 목업은 *"· 다시 부르기"* 를 함께 그렸지만, **실측하면 그 문이 없다.** 집합의
 * 구성원이 안 깨는 사유는 하나뿐이다: 그 사람이 그 채널을 볼 수 없다
 * (`services/channels.ts::channelVisibleSql` — public 이거나 멤버여야 한다. 서버 테스트
 * `handleGroup.test.ts` 의 `blindmember` 가 정확히 그 경우다). 그러면 **다시 불러도 같은
 * 결과다** — 이미 깬 사람만 한 번 더 깨우고 안 깬 사람은 그대로 안 깬다.
 *
 * 갤러리가 이 판단의 선례를 적어 뒀다: *"실패 — 다시 불러도 소용없다 / '다시 부르기'가
 * 없다 — 없는 문은 그리지 않는다"*(`GallerySettings.tsx`). 실제로 여는 문은 그 사람을
 * 채널 멤버로 넣는 것이고, 그 손잡이는 사이드바의 채널 메뉴(`Sidebar.tsx` 의 "멤버")에
 * 있다 — 메시지 행에서 거기로 가는 통로는 없다. 없는 통로를 버튼으로 흉내내지 않고,
 * **무엇이 막았는지를 글자로 말한다.**
 *
 * ## 이름을 말하지 못한다 — 실측
 *
 * 문서의 목업은 *"lint 는 응답이 없다"* 처럼 안 깬 사람을 이름으로 불렀다. 화면은 그것을
 * 할 수 없다: 안 깬 사람은 "부른 집합 − 깬 사람"인데, **집합의 구성원 명단을 화면이 받지
 * 못한다.** `GET /handle-groups/:id` 만 명단을 주고 그 라우트는 `requireAdmin` 이다
 * (실측: `server/src/routes/handleGroupRoutes.ts:61`) — 부르는 사람이 admin 이 아니면
 * 403 이다. 그래서 **수까지만** 말한다("3명 중 2명"). 문서도 그 선을 허용한다: 요구는
 * *"셋을 불렀는데 둘만 깨어난 것"* 을 말하는 것이고, 수가 그것을 말한다.
 *
 * 반면 **구성원 수는 안다** — `HandleGroupRow.memberCount` 는 옵셔널이 아닌 필수 필드이고
 * `GET /accounts` 가 계정 목록과 함께 실어 준다. `Composer.tsx` 의 기존 주석은 *"`HandleGroupRow`
 * 에 수가 없고"* 라고 적었는데 **그것은 지금 틀렸다**(#285 가 그 필드를 넣었다). 그 주석을
 * 함께 고쳤다.
 */
/**
 * 줄 머리의 이름. `mixed` 는 종류를 섞어 불러 아무 쪽도 주장할 수 없는 경우다 —
 * 그때는 이름도 못 말하므로(`NotifiedSummary.groupHandle` 이 `null`) "부른 명단" 이
 * 그 줄이 말할 수 있는 전부다.
 */
const LABEL = { group: '집합', team: '팀', mixed: '부른 명단' } as const;

/**
 * 사유 문장. **종류마다 다르다** — 근거는 아래 렌더 안의 주석에 있다.
 *
 * 상수로 뽑아 둔 이유: 세 문장을 JSX 안의 삼항으로 엮으면 어느 종류가 어느 문장을 받는지
 * 읽을 수 없고, 종류가 하나 늘 때 조용히 빠뜨린다. 여기서는 키가 빠지면 컴파일이 깨진다.
 */
const REASON = {
  group: '— 남은 사람은 이 채널을 볼 수 없다. 채널 멤버로 넣어야 부름이 닿는다.',
  team: '— 남은 팀원은 비활성이거나 이 채널을 볼 수 없다. 팀 설정과 채널 멤버를 보라.',
  mixed: '— 남은 상대에게 부름이 닿지 않았다.',
} as const;

export function NotifiedGapRow({ messageId }: { messageId: string }) {
  const gap = useActiveStore((s) => s.notifiedGaps[messageId]);
  if (!gap) return null;

  return (
    <div
      data-testid="notified-gap"
      data-called={gap.called}
      data-woke={gap.woke}
      data-kind={gap.kind ?? ''}
      className="mt-0.5 flex flex-wrap items-baseline gap-1 text-meta text-warning"
    >
      {/*
        무엇에 대한 줄인지 먼저 말한다 — 문서의 목업이 "집합" 을 앞에 세웠다.

        **팀(#172)이면 "팀" 이라고 말한다.** 이름이 하나뿐이라 사람은 그것이 집합인지 팀인지
        본문에서 알 수 없고, 여기서 "집합" 이라고 부르면 팀 설정을 열어야 할 사람이 집합
        설정을 뒤진다. 종류를 모르면(둘을 섞어 불렀다) 아무 쪽도 주장하지 않는다.
      */}
      <span className="font-medium">
        {LABEL[gap.kind ?? 'mixed']}{gap.groupHandle === null ? '' : ` @${gap.groupHandle}`}
      </span>
      <span>
        {gap.called}명을 불렀는데 {gap.woke}명만 깼다
      </span>
      {/*
        **사유를 함께 말한다.** 수만 말하면 사람이 다음에 무엇을 할지 모르고, 그러면 이 줄은
        놀라게만 하고 끝난다(규칙 05 — 개입 비용).

        **집합에서는 사유가 하나뿐이라 단정한다** — 가시성 판정이 `channelVisibleSql`
        하나이므로 다른 경로가 없다.

        **팀에서는 둘이다.** `services/messages.ts` 가 비활성 팀원을 부르지 않고
        (*"비활성 에이전트는 깰 수 없다"*), `AgentTeamRow.memberCount` 는 그 팀원을 센다 —
        그 어긋남이 이 줄이 뜨는 두 번째 경로다. 그래서 팀에는 집합의 문장을 쓰지 않는다:
        꺼 둔 에이전트 때문에 뜬 줄이 "채널 멤버로 넣어야 한다"고 말하면 사람은 이미
        멤버인 계정을 다시 넣으려 하고, 그것이 규칙 05 가 막는 헛된 개입이다.

        팀 문장이 둘을 **나열하는 것으로 끝나는** 이유: 화면은 어느 쪽인지 가릴 수 없다.
        명단을 주는 라우트는 `GET /teams/:id` 하나이고 그것이 `disabled` 를 싣지만, 그
        조회는 이 줄이 살 값이 아니다 — 발화마다 팀 명단을 받아야 하고, 그래도 "안 깬 팀원"
        은 여전히 못 짚는다(깬 사람의 id 는 헤더가 잘라 준다). 두 문을 다 보여 주고 사람이
        고르게 하는 것이 없는 확신을 꾸미는 것보다 낫다(규칙 06 의 결).
      */}
      <span className="text-fg-muted">{REASON[gap.kind ?? 'mixed']}</span>
    </div>
  );
}
