/**
 * **앱과 서버가 서로 맞는가** — 호환 하한과 그것을 재는 자(#693 후속).
 *
 * ## 왜 "뒤처졌다"만으로는 부족한가
 *
 * 앞 판본은 서버 버전을 앱 버전과 견주기만 했다. 그런데 그 둘은 거의 **항상** 다르다 —
 * 릴리스가 하루에도 여러 번 돌고 서버는 사람이 손으로 재배포하기 때문이다. 그래서 "다르다"
 * 는 거의 언제나 참이고, **거의 언제나 참인 경고는 아무도 안 본다.** 정작 답해야 할 질문은
 * 그것이 아니다:
 *
 *   > 지금 이 서버에서 **이 앱이 제대로 도는가?**
 *
 * 한두 릴리스 뒤진 서버는 대개 멀쩡히 돈다. 반대로 **서버가 있어야 도는 기능**을 앱에
 * 넣은 뒤에는, 한 릴리스만 뒤져도 그 화면이 죽는다. 두 경우는 사람이 할 일이 다르므로
 * (하나는 아무것도 안 해도 되고 하나는 지금 재배포해야 한다) 화면에서 **갈라야 한다.**
 *
 * ## 그래서 하한을 손으로 적는다
 *
 * `MIN_SERVER_VERSION` 은 **이 앱이 요구하는 가장 낮은 서버 버전**이다. 자동으로 따라
 * 오르지 않는다 — 서버 표면에 기대는 것을 앱에 새로 넣은 사람이 그 PR 에서 함께 올린다.
 * 자동으로 올리면(예: 릴리스마다) 다시 "거의 언제나 참"으로 돌아가 아무 뜻이 없어진다.
 *
 * **이 값을 올릴 때는 아래 표에 줄을 더한다.** 표가 없으면 다음 사람이 이 숫자를 내릴
 * 수도 올릴 수도 없다 — 무엇 때문에 그 값인지 아무도 모르기 때문이다.
 */

