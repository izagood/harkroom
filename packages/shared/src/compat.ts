/**
 * **앱과 서버가 서로 맞는가** — 호환 하한과 그것을 재는 자(#693 후속).
 *
 * ## 왜 "뒤처졌다"만으로는 부족한가
 *
 * 앞 판본은 서버 버전을 앱 버전과 견주기만 했다. 그런데 그 둘은 거의 **항상** 다르다 —
 * 릴리스가 하루에도 여러 번 돌고 서버는 사람이 손으로 재배포하기 때문이다. 그래서 "다르다"
 * 는 거의 언제나 참이고, **거의 언제나 참인 경고는 아무도 안 본다.** 정작 답해야 할 질문은
 * 그것이 아니다:
 *
 *   > 지금 이 서버에서 **이 앱이 제대로 도는가?**
 *
 * 한두 릴리스 뒤진 서버는 대개 멀쩡히 돈다. 반대로 **서버가 있어야 도는 기능**을 앱에
 * 넣은 뒤에는, 한 릴리스만 뒤져도 그 화면이 죽는다. 두 경우는 사람이 할 일이 다르므로
 * (하나는 아무것도 안 해도 되고 하나는 지금 재배포해야 한다) 화면에서 **갈라야 한다.**
 *
 * ## 그래서 하한을 손으로 적는다
 *
 * `MIN_SERVER_VERSION` 은 **이 앱이 요구하는 가장 낮은 서버 버전**이다. 자동으로 따라
 * 오르지 않는다 — 서버 표면에 기대는 것을 앱에 새로 넣은 사람이 그 PR 에서 함께 올린다.
 * 자동으로 올리면(예: 릴리스마다) 다시 "거의 언제나 참"으로 돌아가 아무 뜻이 없어진다.
 *
 * **이 값을 올릴 때는 아래 표에 줄을 더한다.** 표가 없으면 다음 사람이 이 숫자를 내릴
 * 수도 올릴 수도 없다 — 무엇 때문에 그 값인지 아무도 모르기 때문이다.
 */

/**
 * 이 앱이 요구하는 **가장 낮은 서버 버전**. 서버가 이보다 낮으면 화면이 "재배포해야
 * 한다"고 말한다(경고가 아니라 고장으로 그린다).
 *
 * ## 올린 기록 — 새 줄은 맨 위에
 *
 * | 값 | 왜 | 무엇이 깨지나 |
 * |---|---|---|
 * | `0.1.167` | `GET /collab/proposals` 가 그 릴리스에 들어갔고(#745), 앱의 협업 탭(#748)이 그것을 부른다 | 레일 다섯째 칸(협업)이 목록을 못 받는다 |
 *
 * **`0.1.167` 보다 낮게 잡을 근거가 없다**: 그 아래의 서버에서는 이 앱의 협업 탭이 확실히
 * 죽는다. 더 높게 잡을 근거도 없다 — 그 뒤로 앱이 새로 기대게 된 서버 표면이 없다.
 * 근거 없이 높이면 멀쩡한 서버가 고장으로 그려지고, 그 순간 이 값은 소음이 된다.
 */
export const MIN_SERVER_VERSION = '0.1.167';

/** `X.Y.Z` 만 견준다. 그 밖의 모양은 견주지 않는다(아래 `compareRelease` 주석). */
const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;

/**
 * 두 릴리스 번호를 견준다. `a < b` 면 음수, 같으면 `0`, 크면 양수.
 * **둘 중 하나라도 `X.Y.Z` 가 아니면 `null`("견줄 수 없다")** 이다.
 *
 * 문자열 비교로 때우지 않는 이유는 하나로 충분하다: `'0.1.9' > '0.1.100'` 이 참이다.
 * murmur 는 이미 세 자리 patch 를 쓰므로(v0.1.174) 그 함정이 **이론이 아니라 지금 일이다.**
 *
 * **`shared` 에 있는 이유**: 이 자를 쓰는 자리가 둘이다 — 화면이 서버와 앱을 견주는 곳과,
 * 하한을 지키는지 재는 회귀선. 두 벌을 두면 한쪽만 고치는 사고가 난다.
 */
export function compareRelease(a: string, b: string): number | null {
  const ma = SEMVER.exec(a);
  const mb = SEMVER.exec(b);
  if (!ma || !mb) return null;
  for (let i = 1; i <= 3; i += 1) {
    const d = Number(ma[i]) - Number(mb[i]);
    if (d !== 0) return d < 0 ? -1 : 1;
  }
  return 0;
}

/**
 * 이 서버 버전으로 **이 앱이 도는가.**
 *
 * 세 갈래를 돌려주는 이유는 셋이 사람에게 다른 일을 시키기 때문이다:
 *   `ok`       — 하한을 넘는다. 앱보다 뒤처졌더라도 **할 일이 없다**
 *   `too-old`  — 하한보다 낮다. **지금 재배포해야 한다**
 *   `unknown`  — 견줄 수 없다(자체 빌드·포크·버전을 안 싣는 서버). 단정하지 않는다
 *
 * `unknown` 을 `ok` 로 눕히지 않는다: 모르는 것을 "괜찮다"고 말하면 화면이 확인하지 않은
 * 것을 확인한 것처럼 주장한다(`docs/design.md` §4).
 */
export function serverCompat(
  serverVersion: string | null,
  minServerVersion: string = MIN_SERVER_VERSION,
): 'ok' | 'too-old' | 'unknown' {
  if (serverVersion === null) return 'unknown';
  const cmp = compareRelease(serverVersion, minServerVersion);
  if (cmp === null) return 'unknown';
  return cmp < 0 ? 'too-old' : 'ok';
}
