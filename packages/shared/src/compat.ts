export const MIN_SERVER_VERSION = '0.3.57';

/** `X.Y.Z` 만 견준다. 그 밖의 모양은 견주지 않는다(아래 `compareRelease` 주석). */
const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;

/**
 * 두 릴리스 번호를 견준다. `a < b` 면 음수, 같으면 `0`, 크면 양수.
 * **둘 중 하나라도 `X.Y.Z` 가 아니면 `null`("견줄 수 없다")** 이다.
 *
 * 문자열 비교로 때우지 않는 이유는 하나로 충분하다: `'0.1.9' > '0.1.100'` 이 참이다.
 * harkroom 는 이미 세 자리 patch 를 쓰므로(v0.1.174) 그 함정이 **이론이 아니라 지금 일이다.**
 *
 * **`shared` 에 있는 이유**: 이 자를 쓰는 자리가 둘이다 — 화면이 서버와 앱을 견주는 곳과,
 * 하한을 지키는지 재는 회귀선. 두 벌을 두면 한쪽만 고치는 사고가 난다.
 */
export function compareRelease(a: string, b: string): number | null {
  const ma = SEMVER.exec(a);
  const mb = SEMVER.exec(b);
  if (!ma || !mb) return null;
  for (let i = 1; i <= 3; i += 1) {
    const d = Number(ma[i]) - Number(mb[i]);
    if (d !== 0) return d < 0 ? -1 : 1;
  }
  return 0;
}

/**
 * 이 서버 버전으로 **이 앱이 도는가.**
 *
 * 세 갈래를 돌려주는 이유는 셋이 사람에게 다른 일을 시키기 때문이다:
 *   `ok`       — 하한을 넘는다. 앱보다 뒤처졌더라도 **할 일이 없다**
 *   `too-old`  — 하한보다 낮다. **지금 재배포해야 한다**
 *   `unknown`  — 견줄 수 없다(자체 빌드·포크·버전을 안 싣는 서버). 단정하지 않는다
 *
 * `unknown` 을 `ok` 로 눕히지 않는다: 모르는 것을 "괜찮다"고 말하면 화면이 확인하지 않은
 * 것을 확인한 것처럼 주장한다(`docs/design.md` §4).
 */
export function serverCompat(
  serverVersion: string | null,
  minServerVersion: string = MIN_SERVER_VERSION,
): 'ok' | 'too-old' | 'unknown' {
  if (serverVersion === null) return 'unknown';
  const cmp = compareRelease(serverVersion, minServerVersion);
  if (cmp === null) return 'unknown';
  return cmp < 0 ? 'too-old' : 'ok';
}
