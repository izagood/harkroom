// murmur daemon 의 엔트리포인트 — **아직 골격이다**(#431 2단계-a).
//
// 이 단계가 닫는 것은 **배포 경로 하나**다: daemon 을 앱과 함께 나가는 Tauri 사이드카로
// 만들고, 그 산출물이 실제로 실행되는지 실물로 확인한다. daemon 이 하는 일 자체 —
// unix 소켓을 열고, 토큰으로 인증하고, 러너를 소유하고, 고아를 재발견하는 것 —— 은
// 전부 2단계-b 다.
//
// ## 여기서 절대 하지 않는 것
//
// - **소켓을 열지 않는다.** IPC 를 만들지 않는다. 그것은 2단계-b 다
// - **pid 파일을 쓰지 않는다.** 파일을 쓰면 아직 아무 계약도 없는 상태를 디스크에 남기게
//   되고, 2단계-b 가 그 형식을 정하기 전에 앱이 그것을 읽으려 들 여지가 생긴다
// - **러너를 띄우지 않는다.** 지금 러너 소유권은 여전히 앱에 있다(`runnerLauncher.ts`)
//
// 그래서 이 프로세스는 받은 인자를 적고 **바로 끝난다**. 대기하지 않는 이유는, 아무 일도
// 하지 않으면서 살아 있는 프로세스는 "daemon 이 떠 있다"는 잘못된 신호를 주기 때문이다 —
// 2단계-b 에서 앱이 소켓 접속으로 생사를 판정하게 되면 그 신호가 실제 의미를 갖는다.
import { parseDaemonArgs, describeArgs } from './args.js';

const args = parseDaemonArgs(process.argv.slice(2));

// stdout 으로 적는다 — 앱이 사이드카를 spawn 하면 이 줄이 그대로 파이프로 온다.
// 로그 파일은 두지 않는다(orca 는 `--log-file` 을 받지만, 그 자리도 2단계-b 가 정한다).
console.log(`murmur daemon (골격, #431 2단계-a) ${describeArgs(args)}`);
