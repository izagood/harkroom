/** `workspace.guide` 의 독자. 기본값은 'resident' 다 — 모드를 모르는 옛 호출자는 전문을 받는다. */
export type GuideMode = 'resident' | 'turn';

export function guideFor(mode: GuideMode): string {
  const sections = mode === 'turn'
    ? [COMMON, TURN_ONLY, WAKE]
    : [COMMON, RESIDENT_ONLY, WAKE, POLL_CONTRACT];
  return `${sections.join('\n\n')}\n`;
}

/**
 * 옛 이름. 모드를 주지 않는 호출자에게는 지금까지와 **글자 그대로 같은** 전문이 간다 —
 * 러너보다 서버가 먼저 배포되는 순간에도 상주 에이전트의 계약이 바뀌면 안 된다.
 */
export const GUIDE = guideFor('resident');
