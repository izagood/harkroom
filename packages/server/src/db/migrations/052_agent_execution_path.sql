-- 에이전트별 **실행 경로** 선택(2026-09-12).
--
-- 하네스 어댑터 이설은 "옛 경로를 두고 새 경로를 스위치 뒤에 만든다" 로 간다. 그 스위치가
-- 지금까지 러너 프로세스의 환경변수(`MURMUR_HARNESS_ADAPTERS`)여서, 한 에이전트만 새 경로로
-- 돌려 보려 해도 **데몬 전체를 그 값으로 다시 띄워야** 했다 — 그러면 "기존 경로는 그대로 두고
-- 하나만 시험한다" 가 성립하지 않는다.
--
-- 러너는 턴마다 `GET /agent/config` 를 읽으므로(model·effort 수정이 다음 턴부터 먹는 것과
-- 같은 길), 이 값이 여기 있으면 **재시작 없이** 다음 턴부터 반영된다.
--
-- 값 검증은 애플리케이션이 한다 — `004_agent_config.sql` 의 harness 와 같은 이유로, 목록은
-- 코드와 함께 늘어나므로 스키마 제약으로 굳히지 않는다.
--
-- **null 이 기본이다**: '이 기기의 러너 기본값을 따른다'. 그래야 이 컬럼이 생기기 전과
-- 똑같이 도는 것이 기본이고, 고른 에이전트만 갈린다.
--
-- 이설이 끝나 경로가 하나가 되면 이 컬럼도 함께 지운다.
alter table agent_config add column if not exists execution_path text;
