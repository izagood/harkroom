-- 멘션 연쇄 깊이(Agents 관제 4단계).
--
-- 왜 필요한가: 에이전트가 남긴 답에는 서로를 부른 `@handle` 이 들어 있다. 사람이 그 답을
-- 복사해 붙여넣거나 에이전트가 답 안에서 다른 에이전트를 부르면, 한 스레드에서 호출이
-- 스스로 이어진다 — 2026-09-08 에 실제로 넷이 연달아 떴고, 사람에게는 몇 개가 도는지 볼
-- 자리조차 없었다. 1단계(#683)가 그것을 보이게 했고 2단계(#685)가 붙여넣기 쪽을 막았지만,
-- **에이전트가 스스로 이어 가는 연쇄**에는 아직 상한이 없다.
--
-- 이 컬럼은 "이 메시지가 연쇄의 몇 번째 고리인가"다:
--   * 사람이 쓴 메시지는 **언제나 0**. 사람은 연쇄의 시작이지 고리가 아니다.
--   * 에이전트가 쓴 메시지는 `그 에이전트를 부른 가장 최근 메시지의 깊이 + 1`.
-- 상한(`MENTION_CHAIN_LIMIT`)에 닿은 메시지는 **다른 에이전트를 부르지 못한다**. 사람에게
-- 가는 알림은 막지 않는다 — 상한은 기계가 스스로 도는 것을 끊는 장치이고, 사람을 부르는
-- 것은 그 스레드에 사람이 필요하다는 뜻이라 오히려 그때 더 필요하다.
--
-- 왜 컬럼인가(계산으로 대신하지 않는가): 깊이는 **그 메시지가 쓰인 순간의 사실**이다.
-- 읽을 때마다 스레드를 거슬러 계산하면 나중에 지운 메시지·수정된 본문 때문에 같은
-- 메시지의 깊이가 달라지고, 그러면 "왜 여기서 끊겼나"를 사후에 설명할 수 없다.
alter table message add column mention_depth int not null default 0;
