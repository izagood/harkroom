-- 채널이 부르는 에이전트의 **부름 방식**(#173 의 확장).
--
-- 지금까지 이 표에 든 에이전트는 하나뿐이었다: **사람이 쓰는 매 줄에 붙는다**(컴포저가
-- 접두를 넣는다). 그래서 "이 채널의 에이전트인데, 필요할 때만 부른다"는 상태를 표현할
-- 길이 없었고 — 조용히 두려면 아예 끄는 수밖에 없었다. 끄면 그 채널에 들어온 사람은
-- 여기서 누구를 부를 수 있는지 화면 어디에서도 알 수 없다(멘션 후보는 전역이라 handle 을
-- 아는 사람만 부른다).
--
-- 그 둘을 한 표의 두 값으로 둔다:
--   always    — 지금까지의 뜻. 컴포저가 매 줄에 접두를 붙인다.
--   available — 접두는 없다. 대신 **부를 수 있는 상대로 화면에 선다**(컴포저의 채널
--               에이전트 줄 · 멘션 후보 맨 위).
--
-- 표를 새로 만들지 않은 이유: 둘은 "이 채널이 어느 에이전트를 데리고 있나"라는 **같은
-- 사실**의 세기 차이다. 표를 나누면 같은 에이전트가 양쪽에 드는 상태가 표현되고, 화면과
-- 서버가 그때 무엇이 이기는지를 각자 정하게 된다.
--
-- 기본값이 'always' 인 이유: 이 마이그레이션 전에 걸려 있던 행은 전부 매 줄에 붙는
-- 에이전트였다. 기본값을 'available' 로 두면 배포 순간 그 채널들의 자동 호출이 조용히
-- 멎는다 — 사람은 무엇이 바뀌었는지 모른 채 답이 오지 않는 채널을 본다.
alter table channel_auto_mention
  add column mode text not null default 'always'
  check (mode in ('always', 'available'));
