-- 팀장. 팀 멘션은 지금 **이름 펼치기**다 — `services/messages.ts` 가 명단을 펼쳐
-- 팀원마다 inbox 항목을 넣고, 그러면 턴이 팀원 수만큼 따로 뜬다. 같은 요청을 넷이
-- 각자 처음부터 풀고 넷이 각자 사람에게 답한다. 그 구조를 "창구 하나"로 바꾸려면
-- 먼저 **팀장이 들어갈 자리**가 데이터에 있어야 한다. 이 컬럼이 그 자리다.
--
-- 이 마이그레이션은 자리만 만든다 — 멘션 해석은 아직 이 값을 읽지 않는다(팬아웃
-- 그대로). 지정과 라우팅을 한 변경에 묶지 않는 이유: 라우팅을 바꾸는 순간 팀 멘션의
-- 뜻이 달라지므로, 그때는 "팀장이 없으면 어떻게 되는가"·"팀장이 비활성이면"·"팀원
-- 보고가 팀장을 어떻게 깨우는가"를 함께 정해야 한다. 지정은 그 논의 없이도 맞다.
alter table agent_team add column lead_account_id uuid;

-- **팀장은 팀원이어야 한다 — 그 규칙을 앱이 아니라 여기서 지킨다.**
--
-- 참조 대상이 `account` 가 아니라 `agent_team_member` 인 것이 요점이다. `account(id)`
-- 를 가리키면 "팀장은 팀원 중 하나" 라는 사실은 라우트의 검사 한 줄에만 살고, 그 검사를
-- 지나치는 경로가 하나 생기는 날(다른 라우트·수동 SQL·이관 스크립트) 팀에 들지도 않은
-- 계정이 팀장으로 앉는다. 그러면 멘션 라우팅을 켜는 날 팀 멘션이 팀 밖의 에이전트를
-- 깨운다 — 부른 사람이 명단에서 확인할 수 없는 대상이다.
--
-- 036 이 팀원 표에 `account.kind` check 를 걸지 않은 판단(*"나중에 바뀌면 뒤늦게 깨지는
-- 제약"*)과 어긋나지 않는다: 그것은 **다른 표의 값이 변하면 조용히 거짓이 되는** check 를
-- 거부한 것이고, 이것은 참조 무결성이다 — 팀원 행이 사라지면 아래 `set null` 이 이 값을
-- 함께 정리하므로 거짓이 되는 순간이 없다.
--
-- `on delete set null (lead_account_id)` 로 **팀장만** 비운다. 열 목록이 없는 그냥
-- `set null` 은 참조하는 열 **전부**(=`id` 까지)를 비우려 들어 PK 에서 터진다. 이 문법은
-- PG 15+ 이고 이 저장소는 개발·테스트·운영이 모두 postgres:16 이다.
--
-- 이 동작이 팀원 제거의 뜻을 그대로 적는다: **팀장을 팀에서 빼면 그 팀은 팀장이 없다.**
-- 앱에서 지우지 않는 이유는 위와 같다 — 빼는 경로가 하나가 아닐 수 있고, 그때 팀장 자리에
-- 팀원이 아닌 계정이 남으면 라우팅이 명단에 없는 에이전트를 깨운다.
--
-- 팀이 지워질 때는 이 제약이 할 일이 없다. 팀원 행은 팀에 cascade 로 매달려 있고
-- (036), 그 cascade 가 도는 시점에 팀 행은 이미 같은 문장에서 사라졌다.
--
-- MATCH SIMPLE(기본값)이라 `lead_account_id` 가 null 이면 제약을 아예 보지 않는다 —
-- 팀장 없는 팀이 정상 상태이므로 그것이 맞다(팀장 지정은 선택이다).
alter table agent_team
  add constraint agent_team_lead_is_member
  foreign key (id, lead_account_id) references agent_team_member (team_id, agent_account_id)
  on delete set null (lead_account_id);
