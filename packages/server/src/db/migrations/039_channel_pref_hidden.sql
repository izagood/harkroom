-- 채널 숨기기(#376). `channel_pref` 에 컬럼을 더한다 — 012(음소거·즐겨찾기)·024(알림 수준)·
-- 038(섹션)과 **같은 계열**(계정별-채널별 선호)이므로 같은 테이블에 두어야 조인이 둘이 되지
-- 않고 한쪽만 정리하는 사고가 나지 않는다. 새 테이블을 만들지 않는 이유가 이것이다.
--
-- 보관(#153)과 한 필드로 합치지 않는다. 보관은 `channel.archived_at` — **채널 전체의 상태**
-- (운영자가 정한다)이고 숨김은 **한 사람의 상태**다. 합치면 한 사람이 치운 채널이 모두에게서
-- 사라지고, 보관된 채널을 개인적으로 치울 방법이 다시 없어진다(#376 이 세운 문제 그대로다).
--
-- 나가기(#344)와도 다른 사실이다. 나가기는 `channel_member` 행을 지워 접근 권한을 버리지만
-- 숨김은 멤버십을 그대로 남긴다 — 그래서 스스로 되돌릴 수 있고 남에게 보이지 않는다.
--
-- 불리언이 아니라 시각인 이유: 012 가 같은 성질의 소프트 상태를 시각으로 둔 선례이고 이유를
-- 그 파일 주석에 적어뒀다 — "언제 숨겼나"가 운영에 필요하고, null 이 곧 "보인다"라서
-- 기본값 backfill 이 필요 없다.
