-- 에이전트가 마지막으로 턴을 마친 시각(#176). **"살아 있는가"가 아니다.**
--
-- 생존은 이미 mcp/presence.ts 의 인메모리 presence 가 답한다(#124) — inbox.poll 이 오면
-- 온라인이고 TTL 이 지나면 오프라인이다. 여기 컬럼은 그 사실을 복제하지 않는다. 같은 사실을
-- 두 곳에 두면 둘이 어긋나고, 어긋나면 어느 쪽이 참인지 아무도 모른다(013_agent_runner_version
-- 이 seen_at 을 매 폴마다 갱신하지 않은 것과 같은 경계다).
--
-- 이 컬럼이 담는 것은 **턴이 끝난 시각** 하나다. 폴이 아니다 — 폴은 할 일이 없어도 25초마다
-- 돌아서(config.ts::pollTimeoutMs) 아무 일도 안 하는 러너를 "방금 활동함"으로 보이게 한다.
-- 발화(message.post)도 아니다 — 도구만 쓰고 끝나는 턴은 발화가 없지만 그것도 활동이다.
--
-- 시각은 **서버가 찍는다**(라우트가 now() 를 쓴다). 러너가 보낸 값을 그대로 저장하면 러너
-- 시계가 앞선 머신에서 "3분 뒤에 활동함"이 화면에 뜬다.
--
-- 이력 테이블이 아니라 현재 상태 하나인 이유: 이슈가 그 좁은 쪽을 먼저 권고했다. 턴 기록을
-- 쌓으면 스키마와 보존 정책이 따라오고, "마지막 활동: 3분 전"에는 그것이 필요 없다.
--
-- backfill 하지 않는다 — 008_agent_runner.sql 이 소유자에 대해 말한 것과 같은 이유로,
-- 추측한 활동 시각은 활동 시각이 아니다. null 이 '아직 한 번도 턴을 돌린 적 없음'이고,
-- 화면은 그것을 '활동 없음'으로만 그린다('죽었다'가 아니다).
alter table agent_config add column last_turn_at timestamptz;
