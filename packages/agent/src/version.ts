/**
 * 러너의 빌드 버전. **번들에 구워진 값이 기본이고, 환경변수가 그것을 덮는다.**
 *
 * ## 왜 환경변수만으로는 부족한가
 *
 * env 는 **누가 러너를 띄웠는가**에 달린 값이다. 앱이 띄운 러너에는 앱이 심어 주지만,
 * 그 경로 밖에서 뜬 러너(사람이 직접 띄운 것, 앞 세대가 남긴 것)에는 아무도 심어 주지
 * 않는다 — 그런 러너는 자기가 어느 번들에서 나왔는지 **알 수 있는데도** `unknown` 을
 * 보고한다. 실측(2026-09-08): 화면의 에이전트 전부가 "버전 모름"이었고, 그중 하나는
 * 앱이 띄우지 않은 러너였다.
 *
 * 번들에 구운 값은 그 질문을 옮긴다 — "누가 띄웠나"가 아니라 **"어느 번들에서 나왔나"**
 * 다. 그리고 그것이 이 값으로 답하려던 질문이다(도는 러너가 새 번들인가).
 *
 * ## 왜 이제는 구울 수 있는가
 *
 * `version.ts` 의 앞 판본은 *"이 저장소의 러너는 `tsx src/main.ts` 로 소스에서 바로
 * 돈다"* 를 근거로 번들 스텝을 두지 않았다. 배포 경로에서는 그 전제가 더 이상 사실이
 * 아니다 — `#431` 이후 러너는 esbuild 로 묶인 **사이드카**로 나간다
 * (`packages/desktop/scripts/sidecar.mjs`). 그 번들 스텝이 이미 있으므로 값 하나를
 * 굽는 데 새로 만들 것이 없다. 소스에서 도는 개발 경로는 구운 값이 없고, 그때는 예전과
 * 똑같이 env 뿐이다.
 *
 * ## 우선순위
 *
 * 1. `AGENT_VERSION` env — **명시적 오버라이드**. 배포·개발이 값을 정하는 자리다.
 * 2. 번들에 구워진 값(`__AGENT_VERSION__`).
 * 3. `unknown` — 둘 다 없다. 거짓 버전을 보내지 않는다(docs/design.md 4절).
 *
 * env 가 위인 이유: 구운 값은 **바꿀 수 없다**. 오버라이드가 아래에 있으면 오버라이드가
 * 아니다.
 */

/**
 * 번들 시점에 esbuild `define` 이 문자열 리터럴로 치환한다. 치환되지 않은 환경
 * (소스에서 도는 개발 경로, 테스트)에서는 **선언되지 않은 식별자**다 — 그래서 `typeof`
 * 로만 만진다. 값으로 읽으면 `ReferenceError` 다.
 */
declare const __AGENT_VERSION__: string | undefined;

const baked = typeof __AGENT_VERSION__ === 'string' && __AGENT_VERSION__ !== ''
  ? __AGENT_VERSION__
  : null;

export const VERSION = process.env.AGENT_VERSION ?? baked ?? 'unknown';
