// 화면 바이트가 **진짜로 살아 있음**을 말하는가(2026-10-25, e2e R2).
//
// 정지 시계(`mentionTurn.ts::probeStall`)는 「기록도 화면도 그대로」일 때만 접는다. 그런데 claude 의
// 도구 확인 창은 사람을 기다리는 동안 대기 표시 `⏺` 를 0.6초마다 그렸다 지웠다 한다(실측 2.1.310:
// `ESC[H\r ESC[9B ESC[38;5;246m⏺ ESC[39m ESC[40;1H ESC[22;2H` 와 같은 자리에 공백을 번갈아). 그
// 바이트를 생존으로 세면 확인 창 앞에 선 턴이 정지로 안 잡히고 30분 무발화 한도까지 간다.
//
// 그래서 **글자가 생긴 바이트만** 센다: 제어 시퀀스·공백·대기 표시 글리프를 걷고도 남는 글자가 있어야
// 한다. 스피너 문구·토큰 수·명령 출력처럼 일이 진행되는 화면은 글자가 남으므로 지금처럼 생존이다.
// 조각 경계에서 잘린 시퀀스가 남으면 생존으로 센다 — 틀려도 지금 동작(모든 바이트가 생존) 쪽이다.

/** 제어 시퀀스: CSI · OSC(BEL 또는 ST 로 끝) · 나머지 두 글자 ESC · C0 제어 문자. */
const CONTROL = /\x1b\[[0-9;?<>=]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)|\x1b[@-_]|[\x00-\x1f\x7f]/g;

/** 대기 중에 깜빡이는 표시. 이것만 그렸다 지우는 바이트는 진행이 아니다. */
const BLINK_GLYPHS = /[⏺●\s]/g;

/** 이 조각이 화면에 진행을 그렸는가. `text` 는 UTF-8 로 풀린 조각이다. */
export function screenShowsProgress(text: string): boolean {
  return text.replace(CONTROL, '').replace(BLINK_GLYPHS, '').length > 0;
}
