-- 에이전트 삭제(#836). **행을 지우지 않는다** — `message.author_id` 가 `account(id)` 를
-- on delete 없이 가리키므로 진짜 delete 는 그 에이전트가 쓴 메시지를 통째로 끌고 가거나
-- (cascade) FK 위반으로 막힌다(지금 모양). 어느 쪽도 답이 아니다: 대화 이력은 그 에이전트
-- 혼자의 것이 아니라 그 자리에 있던 사람들의 것이기도 하다.
--
-- 그래서 삭제는 **명부에서 내리는 것**이다. 행은 남아 과거 메시지의 작성자 이름·아바타를
-- 계속 풀어 주고(디렉터리가 비활성 계정을 빼지 않는 것과 같은 이유), 목록·멘션·팀·배정
-- 에서는 사라진다.
--
-- handle 도 그대로 잡아 둔다. 풀어 주면 다른 에이전트가 그 이름을 가져가고, 과거 메시지의
-- `@murmur` 가 **그 새 에이전트**를 가리키게 된다(본문의 정본은 `<@id>` 지만 화면은 현재
-- handle 로 되돌려 그린다). 이름을 되찾아야 하면 삭제 전에 `PATCH /accounts/:id/handle`
-- 로 옮기는 것이 순서다.
--
-- disabled_at 과 나란히 둔다. 겹쳐 보이지만 다른 사실이다: disabled 는 "꺼 뒀다"(되돌린다),
-- deleted 는 "명부에 없다"(되돌리지 않는다). 한 컬럼으로 합치면 화면이 그 둘을 구분하지
-- 못한다.
alter table account add column deleted_at timestamptz;
