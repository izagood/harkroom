-- 아무도 집지 않은 요청을 **한 번만** 말하기 위한 표시.
--
-- ## 무엇이 문제였나
--
-- 에이전트를 부른 요청은 inbox 항목이 되고, 그 항목을 러너가 집어 턴을 띄운다. 러너가
-- 없으면(PAT 만료로 78 로 물러났거나 · 기계가 꺼졌거나 · 아직 안 떴거나) 그 항목은
-- **아무 일도 일어나지 않은 채 남는다.** 운영자의 앱은 그 사실을 안다(러너 종료 코드를
-- daemon 이 앱에 알린다) — 그러나 스레드에서 기다리는 사람은 **다른 사람·다른 기계**일 수
-- 있고, 그 사람 화면에는 아무 것도 없다. 공유되는 지식은 서버에만 있다.
--
-- 그래서 서버가 그 스레드에 실패 하나를 남긴다. 판정 재료는 `mcp/presence.ts`(폴이 곧
-- presence 신호다)와 이 표의 `read_at` 이고, 이 컬럼은 **이미 말했는가**만 담는다.
--
-- ## 왜 스레드가 아니라 요청에 표시하는가
--
-- 막힌 것은 그 **요청**이다. 스레드에 표시하면 같은 스레드의 다음 요청이 조용히 삼켜진다 —
-- 러너가 죽어 있는 동안 사람이 두 번 부르면 두 번째는 아무 말도 못 듣는다. 통지 자체는
-- 스레드마다 한 줄로 묶지만(한 스레드에 미읽음이 셋이어도 줄은 하나다) 표시는 셋 다에
-- 찍힌다.
--
-- ## 왜 읽음(`read_at`) 으로 대신할 수 없는가
--
-- 읽음은 턴이 **끝날 때** 찍힌다(`mentionScheduler` 가 turn 완료 후 `markRead`). 그래서
-- 정상적으로 도는 긴 턴(최대 30분)도 그동안 미읽음이다 — 미읽음만 보고 판정하면 일하는
-- 에이전트를 죽은 것으로 단정한다. presence 가 그 둘을 가르고, 이 컬럼은 그 판정의 결과를
-- 기억하는 자리다.
alter table inbox add column stale_notified_at timestamptz;

-- 스위퍼의 술어를 그대로 담은 부분 인덱스. 후보는 **미읽음이면서 아직 안 말한 것**뿐이고
-- 그 집합은 정상 운영에서 거의 비어 있다 — 전체 인덱스를 만들면 핫 패스(`inbox.poll` 의
-- 삽입)에 비용만 얹는다.
create index inbox_stale_idx on inbox (created_at)
  where read_at is null and stale_notified_at is null;
