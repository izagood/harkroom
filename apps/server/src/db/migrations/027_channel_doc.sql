-- 채널당 하나(#188). channel_id 가 PK 라 "채널당 하나"를 **스키마가 강제한다** —
-- 애플리케이션 코드가 지키는 규칙이면 새 경로가 생길 때마다 다시 지켜야 한다.
-- 메시지 테이블에 두지 않는 이유: 메시지는 추가(append)이고 문서는 덮어쓰기(replace)다.
-- 한 모델에 넣으면 둘 중 하나가 거짓말한다 — 문서를 메시지로 두면 "밀려나지 않는다"를
-- 메시지 모델 위에 따로 얹는 일이 되고, 그것이 이 테이블이 따로 있는 이유다.
-- 이력 테이블은 만들지 않는다(v1). 대신 라우트가 낙관적 동시성으로 조용한 덮어쓰기를 막는다.
create table channel_doc (
  channel_id uuid primary key references channel(id),
  body text not null default '',
  updated_by uuid not null references account(id),
  -- **밀리초 정밀도로 못박는다(`(3)`).** 낙관적 동시성의 기대값이 이 컬럼을 왕복한다:
  -- 서버는 ISO 문자열(밀리초까지)로 주고 클라이언트는 epoch ms 로 돌려보낸다. 기본
  -- timestamptz 는 마이크로초까지 저장하므로, 그 왕복에서 잘려 나간 마이크로초 때문에
  -- **정확히 맞는 기대값도 어긋난 것으로 판정된다** — 아무도 동시에 고치지 않았는데 409 가
  -- 난다(실측: 두 번째 저장이 곧바로 409). 저장 정밀도를 계약이 표현할 수 있는 만큼으로
  -- 맞추는 것이 비교하는 쪽에서 자르는 것보다 안전하다. 자르는 쪽은 비교문마다 잊을 수 있다.
  updated_at timestamptz(3) not null default now()
);
