/**
 * i18n 의 **타입 계약** — 없는 키를 쓰면 컴파일이 막힌다.
 *
 * ## 왜 라이브러리를 안 쓰나
 *
 * 후보를 넷 놓고 쟀다(`react-i18next` · `@lingui/*` · `next-intl` · 직접).
 *
 * | 후보 | 버린 이유 |
 * |---|---|
 * | `react-i18next` | i18next 본체까지 40KB+ 가 번들에 들어온다. Tauri 앱이라 그 무게가 그대로 배포본이다. 그리고 **타입 안전이 기본이 아니다** — `t('없는.키')` 가 런타임에 키 문자열을 그대로 뱉는다. 얻는 것(로케일 감지·백엔드 로딩·네임스페이스)은 정적 문자열 277개짜리 데스크탑 앱에 쓸 자리가 없다 |
 * | `@lingui/*` | 타입은 좋지만 **바벨/SWC 매크로**가 있어야 제 값을 한다. 이 저장소의 빌드는 vite + tsc 둘뿐이고, 거기에 추출 파이프라인과 `.po` 컴파일 단계를 더하면 **다음 PR 이 화면 하나 옮길 때마다 빌드 단계를 거쳐야 한다** — 그 마찰이 남은 화면 이전을 막는다 |
 * | `next-intl` | Next.js 전용이다. 이 앱은 Next 가 아니다 |
 *
 * 직접 만들면 **번들이 이 파일 셋뿐이고**(런타임 의존 0), 타입 안전이 `keyof` 하나로 나오고,
 * 복수형은 플랫폼이 이미 가진 `Intl.PluralRules` 가 푼다. 이 저장소가 `day.ts` 에서
 * 이미 같은 판단을 했다 — *"로캘을 비워 사용자의 것을 따른다"* 며 `toLocaleDateString`
 * 을 그대로 썼고, 날짜 라이브러리를 넣지 않았다.
 *
 * **다시 재야 하는 조건**을 함께 적어 둔다: 문자열이 1000개를 넘거나, 번역가가 코드
 * 밖에서 작업할 도구(`.po` 편집기)를 요구하거나, 언어별 지연 로딩이 필요해지면 그때는
 * 라이브러리가 이긴다. 셋 다 지금은 아니다.
 */

/**
 * 번역문을 만드는 인자. **원시값만 받는다** — JSX 를 여기 끼우면 판정 함수가 React 를
 * 알게 되고, 그것이 `lib/` 순수 함수를 컨텍스트에 묶는 첫 걸음이다.
 */
export type TransArgs = Record<string, string | number>;

/**
 * 복수형 갈래. `Intl.PluralRules` 의 범주 그대로다 — 우리가 범주를 새로 정의하면
 * 아랍어·러시아어를 붙일 때 그 정의가 모자란다.
 *
 * 영어는 `one`/`other` 둘만 쓰고, 한국어는 `other` 하나만 쓴다. **한국어 번역이
 * `other` 만 적는 것은 누락이 아니라 그 언어의 사실이다** — 그래서 아래 `Plural` 은
 * `other` 만 필수다.
 */
export interface Plural {
  zero?: string;
  one?: string;
  two?: string;
  few?: string;
  many?: string;
  /** 어느 언어에나 있는 유일한 범주. 그래서 이것만 필수다. */
  other: string;
}

/** 한 키의 값. 평문이거나 복수형 묶음이다. */
export type Message = string | Plural;
