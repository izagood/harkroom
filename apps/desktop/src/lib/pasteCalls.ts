/**
 * **붙여넣은 글이 누구를 부르는가** — 그리고 부르지 않게 만드는 방법(2단계).
 *
 * ## 왜 있는가
 *
 * 팀으로 부른 답변을 복사해 이어 가려 붙여넣으면, 본문에 남아 있던 `@handle` 이 **다시
 * 호출**로 읽혀 같은 스레드에 턴이 연달아 뜬다. 서버 규칙은 이미 서 있다 — 인용 줄과
 * 코드 블록 안의 `@handle` 은 부르지 않는다(#298 · #592, `mentionScanText`). 빠진 것은
 * **붙여넣기를 어느 쪽으로 넣을지 사람이 고르는 자리**다.
 *
 * ## 판정을 새로 만들지 않는다
 *
 * 부르는지 여부는 `mentionedHandles`(@harkroom/shared) 하나가 답한다 — 서버가 알림을 만들 때
 * 쓰는 그 함수다. 여기서 자체 정규식을 두면 규칙이 두 벌이 되고, 갈라지는 순간 화면은
 * "부르지 않는다"고 적은 글이 실제로는 넷을 부른다.
 *
 * 인용으로 바꿀 때 붙이는 표시도 같은 이유로 `QUOTE_LINE` 을 기준으로 만든다: 렌더러와
 * 멘션 파서가 인용이라고 부르는 것이 같아야 한다(그 상수의 주석이 근거다).
 */
import { QUOTE_LINE, mentionedHandles } from '@harkroom/shared';

/**
 * 이 글이 실제로 부르는 handle 들(소문자). **아는 이름만 남긴다** — 존재하지 않는
 * `@오타` 는 서버도 부르지 않으므로 사람에게 경고할 것이 아니다.
 *
 * `known` 에는 사람·에이전트뿐 아니라 그룹·팀 handle 도 들어온다(컴포저의 `known` 이 그렇다).
 * 그룹 하나가 여러 사람으로 펼쳐지므로 이 수는 **부를 이름의 수이지 사람 수가 아니다** —
 * 화면 문구도 이름을 세는 말이어야 한다(사람 수를 아는 것은 서버뿐이다).
 */
export function callsInText(text: string, known: ReadonlySet<string>): string[] {
  return mentionedHandles(text).filter((h) => known.has(h));
}

/**
 * 인용으로 바꾼다. 줄마다 `> ` 를 붙이되:
 *
 * - **이미 인용인 줄은 그대로 둔다.** 두 번 붙이면 원문에 없던 겹인용이 생긴다.
 * - **빈 줄은 `>` 로 채운다.** 데스크탑 렌더러는 `>` 가 없는 줄에서 인용을 끊으므로
 *   (`QUOTE_LINE` 주석), 빈 줄을 비워 두면 한 덩이였던 인용이 여러 덩이로 쪼개진다.
 */
export function quoteText(text: string): string {
  return text
    .split('\n')
    .map((line) => (QUOTE_LINE.test(line) ? line : line.trim() ? `> ${line}` : '>'))
    .join('\n');
}

/**
 * 부르는 이름이 이만큼이면 **보내기 전에 한 번 묻는다.**
 *
 * 왜 3 인가: 둘까지는 사람이 의도해서 부르는 일이 흔하다(질문 하나에 담당 둘). 셋부터는
 * 복사한 본문이 그대로 실려 온 경우가 대부분이고, 그것이 이 개편을 낳은 사고다. 이 값은
 * 폭주를 막는 마지막 문이 아니라 **되돌릴 수 있는 지점에 세운 확인**이다 — 보내고 나면
 * 턴은 이미 떴고, 그때는 중단(3단계)밖에 남지 않는다.
 */
export const MANY_CALLS = 3;
